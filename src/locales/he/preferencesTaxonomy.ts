/** כל התגיות של קבוצה - נוח לבדיקת "האם כל התגיות בקבוצה נבחרו". */
export function getGroupTagCount(categoryId: TripAddCategory, group: string): number {
  const category = PREFERENCES_TAXONOMY.find((c) => c.id === categoryId);
  return category?.groups.find((g) => g.group === group)?.tags.length ?? 0;
}

/**
 * בחירות המשתמש בתוך קטגוריה אחת: קבוצות-משנה שנבחרו בשלמותן
 * ("קטגוריה מהירה") + תגיות ספציפיות שנבחרו בנפרד (אחרי פתיחת קבוצה).
 * מוגדר כאן (ולא ב-app/preferences/steps.ts) כדי ש-preferencesService.ts
 * (שכבת שירות) יוכל לייבא את הטיפוס בלי לייבא משכבת app/.
 */
export interface CategorySelectionState {
  groups: string[];
  tags: string[];
}

export type TaxonomySelections = Record<TripAddCategory, CategorySelectionState>;

export function emptyTaxonomySelections(): TaxonomySelections {
  return PREFERENCES_TAXONOMY.reduce((acc, category) => {
    acc[category.id] = { groups: [], tags: [] };
    return acc;
  }, {} as TaxonomySelections);
}

/** סה"כ בחירות (קבוצות + תגיות) בקטגוריה אחת - לתג המספר בכותרת השלב. */
export function countCategorySelections(selection: CategorySelectionState | undefined): number {
  if (!selection) return 0;
  return selection.groups.length + selection.tags.length;
}
